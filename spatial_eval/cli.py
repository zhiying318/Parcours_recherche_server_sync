def main():
    parser = argparse.ArgumentParser(description="Spatial QA evaluation (modular).")
    parser.add_argument("--backend", required=True, choices=["qwen", "internvl", "qwen3vl", "qwen3-vl-thinking", "gemma3", "gemma4", "qwen3.5vl", "qwen3.5vl-thinking", "qwen3vl-logits", "mistral", "openai"])
    parser.add_argument("--model_id", required=True)
    parser.add_argument("--image_json", default=None)
    parser.add_argument("--image_pairs_json", default=None)
    parser.add_argument("--pair_mode", action="store_true", help="Evaluate with two images per query (COMFORT pairs).")
    parser.add_argument("--pov_mode", action="store_true", help="Evaluate POV image-choice: 1 external image + 2 POV option images.")
    parser.add_argument("--image_triples_json", default=None, help="JSON with external_img/correct_pov_img/distractor_pov_img entries.")
    parser.add_argument("--pov4_mode", action="store_true", help="Evaluate 4-choice POV: 1 external image + 4 POV images as options.")
    parser.add_argument("--image_quads_json", default=None, help="JSON with external_img/pov_front/pov_back/pov_left/pov_right/correct_cam entries.")
    parser.add_argument("--out_csv", required=True)
    parser.add_argument("--cuda_visible_devices", default=None) # Use CUDA_CISIBLE_DEVICES=0 at the beginning of the command in cli to avoid device_map="auto" to see all GPUs such that we have AttnImplementation Error:RuntimeError(FlashAttention only supports Ampere GPUs or newer.)
    parser.add_argument("--device_map", default="auto")
    parser.add_argument("--answer_length", required=False, default="short", choices=["short", "middle", "long"], help="The length of the answer to be generated by the model, which may affect the choice of max_new_tokens in generation.")
    parser.add_argument("--enable_thinking", action="store_true", help="Enable thinking mode for backends that support it.")

    # choose ask mode: yes/no or multiple-choice
    parser.add_argument("--ask_mode", choices=["yn", "mcq"], default="yn")

    # super parameters
    parser.add_argument("--max_new_tokens_where", type=int, default=64)
    parser.add_argument("--max_new_tokens_yn", type=int, default=8)
    parser.add_argument("--max_new_tokens_mcq", type=int, default=8)
    parser.add_argument("--mcq_seed", type=int, default=0)
    parser.add_argument("--mcq_prompt_note", default="", help="Optional extra sentence inserted into single-image MCQ prompts. insert (with_aligned_prompts)")
    parser.add_argument("--mistral_reasoning_effort", choices=["none", "high"], default=None)
    parser.add_argument("--mistral_temperature", type=float, default=None)
    parser.add_argument("--mistral_top_p", type=float, default=None)
    parser.add_argument(
        "--openai_reasoning_effort",
        choices=["none", "low", "medium", "high", "xhigh", "max"],
        default=None,
    )
    parser.add_argument(
        "--openai_reasoning_summary",
        choices=["auto", "concise", "detailed"],
        default=None,
        help="Request a summary (Responses API only); save it outside CSV.",
    )
    parser.add_argument(
        "--openai_api_mode",
        choices=["chat_completions", "responses"],
        default="chat_completions",
    )
    parser.add_argument(
        "--openai_reasoning_jsonl",
        default=None,
        help="Optional reasoning sidecar JSONL path.",
    )
    parser.add_argument("--openai_timeout", type=float, default=120.0)
    parser.add_argument("--openai_max_retries", type=int, default=5)
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Append to a compatible CSV and skip completed samples.",
    )

    args = parser.parse_args()

    if args.cuda_visible_devices is not None:
        os.environ["CUDA_VISIBLE_DEVICES"] = str(args.cuda_visible_devices)

    dtype = None if args.backend in ("mistral", "openai") else get_dtype()

    backend = build_backend(
        args.backend,
        args.model_id,
        dtype=dtype,
        device_map=args.device_map,
        enable_thinking=args.enable_thinking,
        mistral_temperature=args.mistral_temperature,
        mistral_top_p=args.mistral_top_p,
        mistral_reasoning_effort=args.mistral_reasoning_effort,
        openai_reasoning_effort=args.openai_reasoning_effort,
        openai_reasoning_summary=args.openai_reasoning_summary,
        openai_api_mode=args.openai_api_mode,
        openai_reasoning_jsonl=args.openai_reasoning_jsonl,
        openai_timeout=args.openai_timeout,
        openai_max_retries=args.openai_max_retries,
    )

    if args.pov4_mode:
        if not args.image_quads_json:
            raise ValueError("--pov4_mode requires --image_quads_json")
        with open(args.image_quads_json, "r", encoding="utf-8") as f:
            image_quads = json.load(f)
        asker = MCQPovFourAsker(
            seed=args.mcq_seed,
            max_new_tokens=args.max_new_tokens_mcq,
        )
        run_eval_pov_four(
            backend=backend,
            image_quads=image_quads,
            output_csv=args.out_csv,
            asker=asker,
        )
    elif args.pov_mode:
        if not args.image_triples_json:
            raise ValueError("--pov_mode requires --image_triples_json")
        with open(args.image_triples_json, "r", encoding="utf-8") as f:
            image_triples = json.load(f)
        asker = MCQPovAsker(
            seed=args.mcq_seed,
            max_new_tokens=args.max_new_tokens_mcq,
        )
        run_eval_pov(
            backend=backend,
            image_triples=image_triples,
            output_csv=args.out_csv,
            asker=asker,
        )
    elif args.pair_mode:
        if not args.image_pairs_json:
            raise ValueError("--pair_mode requires --image_pairs_json")
        with open(args.image_pairs_json, "r", encoding="utf-8") as f:
            image_pairs = json.load(f)
        asker = MCQPairAsker(
            seed=args.mcq_seed,
            max_new_tokens_mcq=args.max_new_tokens_mcq,
            answer_length=args.answer_length,
        )
        run_eval_pair(
            backend=backend,
            image_pairs=image_pairs,
            output_csv=args.out_csv,
            asker=asker,
            resume=args.resume,
        )
    else:
        if not args.image_json:
            raise ValueError("--image_json is required when not using --pair_mode")
        with open(args.image_json, "r", encoding="utf-8") as f:
            image_paths = json.load(f)
        if args.ask_mode == "yn":
            asker = YNAsker(
                max_new_tokens_where=args.max_new_tokens_where,
                max_new_tokens_yn=args.max_new_tokens_yn,
            )
        else:
            asker = MCQAsker(
                seed=args.mcq_seed,
                max_new_tokens_mcq=args.max_new_tokens_mcq,
                answer_length=args.answer_length,
                prompt_note=args.mcq_prompt_note,
            )
        run_eval(
            backend=backend,
            image_paths=image_paths,
            output_csv=args.out_csv,
            asker=asker,
            resume=args.resume,
        )

    print(f"Saved: {args.out_csv}")

if __name__ == "__main__":
    main()
